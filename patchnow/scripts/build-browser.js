#!/usr/bin/env node
// Bundles the dependency-free parts of patchnow (core matcher + lockfile parsers + runtime table)
// into one browser script that exposes window.PatchCore and window.PatchParsers.
// The PATCH site's in-browser checker loads this file, so the site and the CLI share the same semantics.
'use strict';
const fs = require('fs');
const path = require('path');
const src = path.join(__dirname, '..', 'src');
const out = process.argv[2] || path.join(__dirname, '..', 'dist', 'patchnow-browser.js');
const mods = {
  './npm': 'parsers/npm.js', './composer': 'parsers/composer.js', './python': 'parsers/python.js', './toml': 'parsers/toml.js',
  './go': 'parsers/go.js', './cargo': 'parsers/cargo.js',
};
let body = '';
for (const [id, file] of Object.entries(mods)) {
  if (!file) continue;
  body += `defs[${JSON.stringify(id)}] = function (module, exports, require) {\n${fs.readFileSync(path.join(src, file), 'utf8')}\n};\n`;
}
const yarn = fs.readFileSync(path.join(src, 'parsers/yarn.js'), 'utf8').replace("const YAML = require('yaml');", "const YAML = { parse() { throw new Error('Yarn Berry lockfiles are supported by the CLI only'); } };");
body += `defs['./yarn'] = function (module, exports, require) {\n${yarn}\n};\n`;
const table = fs.readFileSync(path.join(src, 'data/runtime-advisories.json'), 'utf8');
const pkg = require('../package.json');
const bundle = `/*! patchnow ${pkg.version} browser build (MIT). Generated by scripts/build-browser.js — do not edit. */
${fs.readFileSync(path.join(src, 'core.js'), 'utf8')}
(function (root) {
  'use strict';
  var defs = {}, cache = {};
  function req(id) {
    if (cache[id]) return cache[id].exports;
    var m = cache[id] = { exports: {} };
    defs[id](m, m.exports, req);
    return m.exports;
  }
${body}
  var npm = req('./npm'), composer = req('./composer'), py = req('./python'), go = req('./go'), cargo = req('./cargo'), yarn = req('./yarn');
  var KINDS = {
    'package-lock.json': function (t) { return npm.parsePackageLock(t); },
    'package.json': function (t) { return npm.parsePackageJson(t); },
    'yarn.lock': function (t) { return yarn.parseYarnLock(t); },
    'composer.lock': function (t) { return composer.parseComposerLock(t); },
    'requirements.txt': function (t) { return py.parseRequirements(t).packages; },
    'poetry.lock': function (t) { return py.parsePoetryLock(t); },
    'go.mod': function (t) { return go.parseGoMod(t).packages; },
    'Cargo.lock': function (t) { return cargo.parseCargoLock(t); }
  };
  root.PatchParsers = { KINDS: KINDS, npm: npm, composer: composer, python: py, go: go, cargo: cargo, yarn: yarn, runtimeAdvisories: ${table.trim()}, version: ${JSON.stringify(pkg.version)} };
})(typeof self !== 'undefined' ? self : this);
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, bundle);
console.log('wrote ' + path.relative(process.cwd(), out) + ' (' + bundle.length + ' bytes)');
